-- Oracle only. Create in an EMPTY disposable schema; no automatic drops.
CREATE TABLE LAB_VENDOR (
    V_CODE NUMBER(6) PRIMARY KEY,
    V_NAME VARCHAR2(40) NOT NULL UNIQUE,
    V_STATE CHAR(2) NOT NULL
);
CREATE TABLE LAB_PRODUCT (
    P_CODE VARCHAR2(10) PRIMARY KEY,
    P_DESCRIPT VARCHAR2(80) NOT NULL,
    P_INDATE DATE NOT NULL,
    P_QOH INTEGER DEFAULT 0 NOT NULL CHECK (P_QOH >= 0),
    P_MIN SMALLINT DEFAULT 0 NOT NULL CHECK (P_MIN >= 0),
    P_PRICE NUMBER(8, 2) NOT NULL CHECK (P_PRICE >= 0),
    P_DISCOUNT NUMERIC(4, 2) DEFAULT 0 NOT NULL
        CHECK (P_DISCOUNT BETWEEN 0 AND 1),
    V_CODE NUMBER(6) REFERENCES LAB_VENDOR (V_CODE)
);
CREATE TABLE LAB_CUSTOMER (
    CUS_CODE NUMBER(8) PRIMARY KEY,
    CUS_LNAME VARCHAR2(30) NOT NULL
);
CREATE TABLE LAB_PRICE_AUDIT (
    P_CODE VARCHAR2(10) NOT NULL,
    OLD_PRICE NUMBER(8, 2),
    NEW_PRICE NUMBER(8, 2),
    ACTION VARCHAR2(6) NOT NULL
);
