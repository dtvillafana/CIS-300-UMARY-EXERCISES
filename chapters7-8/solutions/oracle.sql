-- Procedure performs an operation; function returns a value. A SQL-invoked
-- function isn't unrestricted: avoid hidden DML/COMMIT and unsupported types.
-- OB6: CREATE trigger before test DML because Oracle DDL commits.
CREATE OR REPLACE TRIGGER LAB_PRODUCT_AUDIT
AFTER INSERT OR UPDATE OR DELETE ON LAB_PRODUCT
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO LAB_PRICE_AUDIT VALUES (:NEW.P_CODE, NULL, :NEW.P_PRICE, 'INSERT');
    ELSIF UPDATING THEN
        INSERT INTO LAB_PRICE_AUDIT VALUES (:NEW.P_CODE, :OLD.P_PRICE, :NEW.P_PRICE, 'UPDATE');
    ELSIF DELETING THEN
        INSERT INTO LAB_PRICE_AUDIT VALUES (:OLD.P_CODE, :OLD.P_PRICE, NULL, 'DELETE');
    END IF;
END;
/
INSERT INTO LAB_PRODUCT (P_CODE, P_DESCRIPT, P_INDATE, P_PRICE)
VALUES ('T1', 'Trigger test', DATE '2026-10-14', 5);
