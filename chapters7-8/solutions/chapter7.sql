JOIN invoice AS i ON i.CUS_CODE = c.CUS_CODE
JOIN line AS l ON l.INV_NUMBER = i.INV_NUMBER
WHERE i.INV_DATE >= '2026-10-01' AND i.INV_DATE < '2026-11-01'
ORDER BY l.INV_NUMBER, l.LINE_NUMBER;
-- 7.8b/c: retain the same groups when HAVING is added.
SELECT c.CUS_CODE, SUM(l.LINE_UNITS * l.LINE_PRICE) AS Revenue
FROM customer AS c JOIN invoice AS i ON i.CUS_CODE = c.CUS_CODE
JOIN line AS l ON l.INV_NUMBER = i.INV_NUMBER
WHERE i.INV_DATE >= '2026-10-01' AND i.INV_DATE < '2026-11-01'
GROUP BY c.CUS_CODE HAVING SUM(l.LINE_UNITS * l.LINE_PRICE) >= 100
ORDER BY Revenue DESC, c.CUS_CODE;
-- 7.8d: don't join lines; an empty invoice is still an invoice.
